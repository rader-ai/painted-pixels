const POST = `
// ======== adding an action ========
// ACTIONS were filled in as the kit loaded. To add one of your own: addAction('wave', [[.4, {near: [24, 6]}], [1.2, {near: null}]]);
function addAction(name, list){
  const keys = [[0, {...POSE0}]];
  for (const [at, ch] of list) keys.push([at, {...keys[keys.length - 1][1], fx: undefined, flow: 0, ...ch}]);
  ACTIONS[name] = {keys, dur: keys[keys.length - 1][0]};
}

// ======== running a place ========
// Runs a place on a canvas of DW x DH, the way the app does: wind, life, the place itself, then
// any puffs and sparkles. Optional: who ('guy' or 'girl'), seated (false for someone walking),
// walking (true moves the ground under them at speed, in logical pixels a second). If you need to
// crop it, scale it or pause it off screen, write your own loop: this one is only eighteen lines.
function runPlace(canvas, id, {who = 'guy', seated = true, walking = false, speed = 9} = {}){
  canvas.width = DW; canvas.height = DH;
  const g = canvas.getContext('2d'), k = ck(g);
  g.imageSmoothingEnabled = false;
  k.who = who; k.live = true; k.light = LIGHTS[id];
  let last = performance.now() / 1000;
  life.awake = true;
  function frame(){
    const now = performance.now() / 1000, dt = Math.min(.1, now - last);
    last = now;
    windy += ((state.layers.rain.on ? 1.7 : 1) - windy) * Math.min(1, dt * .5);
    scene.walk += ((walking ? 1 : 0) - scene.walk) * Math.min(1, dt * 3);
    scene.speed = speed * scene.walk;
    scene.scroll += dt * scene.speed;
    if (!reduceMotion) windTick(now, dt);
    lifeTick(dt, id, who, seated);
    PLACES[id].draw(g, now, dt, k);
    lifeFxDraw(k, dt);
    scene.beat *= Math.pow(.02, dt); scene.q *= Math.pow(.01, dt);
    requestAnimationFrame(frame);
  }
  requestAnimationFrame(frame);
}
`;

const out = PREAMBLE + '\n' + BLOCKS.map(block).join('\n') + POST;
const dest = join(HERE, '../assets/kit.js');
writeFileSync(dest, out);
console.log(`kit.js: ${out.split('\n').length} lines, ${(out.length / 1024).toFixed(0)} KB`);

// An index, so nobody has to read the kit to find out what's in it
const entry = /^(?:function (\w+)\(([^)]*)\)|(?:const|let) (\w+) = (?:\(([^)]*)\) =>|(\w+) =>|)|    (\w+)\(([^)]*)\)\{)/;
const index = ['# What\'s in the kit', '', 'Generated by `scripts/build-kit.mjs` from Lofi Studio\'s `index.html`, so don\'t edit it. Line numbers are in `assets/kit.js`: read just the lines you need, since the lines are long. A guide may name something that isn\'t here. That\'s one world\'s own code from Lofi Studio, which you can read as an example at https://github.com/rader-ai/lofi-studio/blob/main/index.html.', ''];
const kitLines = out.split('\n');
let inPainter = false;
kitLines.forEach((line, i) => {
  const head = line.match(/^\/\/ ======== (.+) ========$/);
  if (head){ index.push('', `## ${head[1]}`, ''); return; }
  if (/^function painter\(/.test(line)) inPainter = true;
  if (inPainter && /^}/.test(line)) inPainter = false;
  const m = line.match(entry);
  if (!m) return;
  if (m[6] && !inPainter) return;                                 // only the painter's methods are indented entries
  if (m[6] && ['if', 'for', 'while', 'switch', 'function'].includes(m[6])) return;
  const name = m[1] || m[3] || (m[6] && 'p.' + m[6]), args = m[2] ?? m[4] ?? m[5] ?? m[7], isFn = args !== undefined;
  if (!name) return;
  let note = '';
  for (let j = i - 1; j >= 8 && j >= i - 6 && /^\s*\/\//.test(kitLines[j]) && !/^\/\/ ========/.test(kitLines[j]); j--) note = kitLines[j].trim().replace(/^\/\/\s*/, '') + (note ? ' ' + note : '');
  if (note.length > 150) note = note.slice(0, 147).replace(/\s+\S*$/, '') + '...';
  index.push(`- \`${name}${isFn ? `(${args})` : ''}\`: line ${i + 1}${note ? '. ' + note : ''}`);
});
writeFileSync(join(HERE, '../references/kit-index.md'), index.join('\n') + '\n');
console.log(`kit-index.md: ${index.filter(l => l.startsWith('- ')).length} names`);
