// Copies the painting toolkit out of Lofi Studio's index.html into assets/kit.js, so the same
// tools work in any page. Run it after the toolkit changes, with a checkout of
// https://github.com/rader-ai/lofi-studio to copy from:
//   node build-kit.mjs path/to/lofi-studio/index.html
// Each block is found by its first and last lines, so a block that has moved still comes across,
// and one that has gone stops the build rather than quietly leaving a hole.
